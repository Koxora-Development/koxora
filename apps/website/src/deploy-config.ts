import type { Locale } from './routes';
import type { Redirect } from './routes';
// Hosting configuration, generated from the route table and the hosting
// contract rather than written by hand. Every redirect, every header and the
// language decision exist once, in the application, and each web server in
// front of the site is a rendering of them.
//
// These functions are pure: they take the build data and return text. A unit
// test renders them and asserts the properties that matter, so a change that
// would break a deployment fails before anything is deployed.

/** Paths that must never reach a client, as a regular expression. */
const hiddenPathPattern = '(^|/)(?!\\.well-known/)[._]';

export interface CacheRule {
  prefix: string;
  value: string;
}
/** Everything a web server configuration is rendered from. */
export interface HostingInput {
  locales: readonly Locale[];
  defaultLocale: Locale;
  redirects: readonly Redirect[];
  /** Response headers, as the hosting contract defines them. */
  headers: Readonly<Record<string, string>>;
  cacheRules: readonly CacheRule[];
  documentCacheControl: string;
  languageCookieName: string;
  generator?: string;
}
function header(generator: string): string {
  return `# Generated by ${generator}. Do not edit by hand.`;
}
/** Escapes a literal path for use inside a regular expression. */
function literal(path: string): string {
  return path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * How many entries of `Accept-Language` the Apache fragment examines.
 *
 * The container runs the authoritative algorithm itself: `renderNginx` loads
 * `src/nginx/koxora-language.js` through the njs module, which orders the
 * whole list by quality value and honours a `q=0` refusal exactly as
 * `src/language.ts` does. That is the production path.
 *
 * `renderApacheStatic` is for a host that serves the emitted files without
 * the container. A rewrite condition cannot compare quality values at all, so
 * that fragment reads the list in written order and stops at the first entry
 * this site has a language for. Browsers write the list in descending
 * quality, so it agrees with the algorithm on every header a browser sends,
 * and a hand-written header whose quality values contradict its order is
 * where the two differ. The deployment guide records that this applies to the
 * no-container fragment only.
 *
 * Eight entries are far more than any browser sends; a longer list falls
 * through to the fallback language.
 */
export const acceptLanguageDepth = 8;

/**
 * One pattern per list position and language, in the order a server must try
 * them: position first, so the earliest supported entry wins, and no capture
 * group, so nothing depends on how a server exposes captures to a value.
 */
export interface AcceptLanguagePattern {
  locale: Locale;
  /** Zero-based position in the `Accept-Language` list. */
  position: number;
  pattern: string;
}
export function acceptLanguagePatterns(
  locales: readonly Locale[],
  depth: number = acceptLanguageDepth,
): AcceptLanguagePattern[] {
  const patterns: AcceptLanguagePattern[] = [];
  for (let position = 0; position < depth; position += 1) {
    const prefix = position === 0 ? '' : `(?:[^,]*,){${position}}`;
    for (const locale of locales)
      patterns.push({
        locale,
        position,
        pattern: `^${prefix}\\s*${locale}(?:-[A-Za-z0-9]+)*\\s*(?:[,;]|$)`,
      });
  }
  return patterns;
}

/**
 * The NGINX configuration of the website container. It is included inside the
 * `http` block, so it carries its own maps, and it binds a loopback address
 * only: the public host terminates TLS and proxies to it.
 *
 * Four things here matter in production:
 *
 * - The language of the address that names no language is decided by
 *   `src/nginx/koxora-language.js`, loaded through the njs module. That file
 *   is the same algorithm as `src/language.ts`, quality values and `q=0`
 *   included, and a test compares the two over a generated matrix.
 * - `absolute_redirect off` keeps every redirect relative, so a reader never
 *   receives a `Location` naming the container's own internal address.
 * - That negotiated answer is never cached, and says so with `Vary`.
 * - Every header is set once on the server, and no location adds one, because
 *   an `add_header` inside a location replaces the inherited set instead of
 *   extending it.
 */
export function renderNginx({
  locales,
  redirects,
  headers,
  cacheRules,
  documentCacheControl,
  listenPort,
  healthPath = '/healthz',
  generator = 'apps/website/scripts/emit-site.mjs',
  root = '/usr/share/nginx/html',
  njsModulePath = '/etc/nginx/njs/koxora-language.js',
  accessLog = '/dev/stdout',
  errorLog = '/dev/stderr warn',
}: HostingInput & {
  listenPort: number;
  healthPath?: string;
  root?: string;
  /** Where the image puts the njs module this configuration imports. */
  njsModulePath?: string;
  /** Overridden when the container's own streams are not available. */
  accessLog?: string;
  errorLog?: string;
}): string {
  const cacheMap = [
    `    default "${documentCacheControl}";`,
    // The negotiated root must never be stored by a browser or a network
    // cache: the next reader of the same address can need the other language.
    `    "/" "no-store";`,
    ...cacheRules.map(
      (rule) => `    "~^${literal(rule.prefix)}" "${rule.value}";`,
    ),
  ].join('\n');
  const languageMaps = `# The language of the address that names no language. The njs module is the
# algorithm of apps/website/src/language.ts, quality values and the q=0
# refusal included; a map and a rewrite condition cannot compare quality
# values, which is why this is not written as a map. It reads this site's own
# cookie and Accept-Language, and can answer nothing but the languages it was
# built with, so no request can name a redirect target of its own.
js_import koxora from ${njsModulePath};
js_set $koxora_language koxora.rootLanguage;
# Only the address without a language is negotiated, and the handler above is
# therefore read on no other request. Every other address names its language
# and is served as asked, whatever a reader chose before.
map $uri $koxora_root_redirect {
    default "";
    "/" "/$koxora_language/";
}
map $uri $koxora_cache_control {
${cacheMap}
}
# The negotiated answer depends on both, and a shared cache has to know.
map $uri $koxora_vary {
    default "";
    "/" "Cookie, Accept-Language";
}`;
  const redirectLocations = redirects
    .flatMap((entry) => {
      const withoutSlash = entry.from.replace(/\/$/, '');
      const targets = [entry.from, ...(withoutSlash ? [withoutSlash] : [])];
      // Both spellings answer directly, so an address without its trailing
      // slash does not take a second hop through the normalization below.
      return targets.map(
        (from) =>
          `    location = ${from} { return ${entry.status} "${entry.to}$is_args$args"; }`,
      );
    })
    .join('\n');
  return `${header(generator)}
# Container configuration for the Koxora marketing website. Include it inside
# the http block, which is what /etc/nginx/conf.d/*.conf does. The public host
# owns the domain, terminates TLS and proxies to this address.

${languageMaps}

server {
    # IPv4 only, deliberately: the public host proxies to the loopback address
    # of this container, and an IPv6 listener is one more way for the
    # container to refuse to start where IPv6 is switched off.
    listen ${listenPort};
    server_name _;
    root ${root};
    index index.html;
    # Relative redirects only: a reader must never be sent to the container's
    # own address, which is what a generated absolute Location would name.
    absolute_redirect off;
    port_in_redirect off;
    server_tokens off;
    charset utf-8;
    # The address of the proxy, not of a reader. Visitor addresses are logged
    # by the public host, which is the one place that has to see them.
    access_log ${accessLog};
    error_log ${errorLog};
    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    gzip_types text/plain text/css text/javascript application/javascript application/json application/manifest+json application/xml image/svg+xml;

${Object.entries(headers)
  .map(([name, value]) => `    add_header ${name} "${value}" always;`)
  .join('\n')}
    add_header Cache-Control $koxora_cache_control always;
    # An empty value adds no header, so only the negotiated root carries this.
    add_header Vary $koxora_vary always;

    error_page 404 /404.html;

    # Container liveness, answered without touching the published files.
    location = ${healthPath} {
        access_log off;
        default_type text/plain;
        return 200 "ok\\n";
    }

    # Build artefacts and dot files are never public, whatever ends up in the
    # root. The standard well-known directory is the one exception.
    location ~ "${hiddenPathPattern}" { return 404; }

    # Exactly one address per page: the missing trailing slash is added before
    # anything is served, and the query string survives the hop. The pattern
    # never matches a name with a suffix, so a file keeps its own address.
    location ~ "^(/(?:[A-Za-z0-9._~-]+/)*[A-Za-z0-9~-]+)$" {
        return 301 "$1/$is_args$args";
    }

${redirectLocations}

${locales
  .map(
    (locale) => `    location /${locale}/ {
        error_page 404 /${locale}/404.html;
        try_files $uri $uri/index.html =404;
    }`,
  )
  .join('\n')}

    location / {
        if ($koxora_root_redirect != "") {
            # Temporary on purpose: the answer depends on the reader, so it
            # must stay re-askable and must never be cached as permanent.
            # The query string is appended explicitly: a return whose target
            # comes from a variable does not carry it over, which is how a
            # campaign parameter would be lost on the way to the language.
            return 302 "$koxora_root_redirect$is_args$args";
        }
        try_files $uri $uri/index.html =404;
    }
}
`;
}

/**
 * The main NGINX configuration of the container.
 *
 * It exists because `load_module` is only valid in the main context, so the
 * site configuration above cannot load the njs module itself, and because an
 * image's own default configuration is not something to guess at. Everything
 * writable sits under a temporary directory, so the container can run with a
 * read-only file system.
 */
export function renderNginxMain({
  loadModulePath = 'modules/ngx_http_js_module.so',
  includeGlob = '/etc/nginx/conf.d/*.conf',
  mimeTypesPath = 'mime.types',
  temporaryDirectory = '/tmp',
  accessLog = '/dev/stdout',
  errorLog = '/dev/stderr warn',
  generator = 'apps/website/scripts/emit-site.mjs',
}: {
  loadModulePath?: string;
  includeGlob?: string;
  mimeTypesPath?: string;
  temporaryDirectory?: string;
  accessLog?: string;
  errorLog?: string;
  generator?: string;
} = {}): string {
  return `${header(generator)}
# Main configuration of the Koxora website container.
#
# The njs module carries the language negotiation, and load_module is valid
# only here, which is why this file is generated rather than inherited from
# the base image. No user directive is set: the workers then run unprivileged
# and the published files are read-only to them either way.

load_module ${loadModulePath};
worker_processes auto;
pid ${temporaryDirectory}/nginx.pid;
error_log ${errorLog};

events {
    worker_connections 1024;
}

http {
    include ${mimeTypesPath};
    default_type application/octet-stream;
    server_tokens off;
    sendfile on;
    tcp_nopush on;
    keepalive_timeout 30;
    types_hash_max_size 4096;
    # The container needs no writable layer of its own.
    client_body_temp_path ${temporaryDirectory}/nginx-client-body;
    proxy_temp_path ${temporaryDirectory}/nginx-proxy;
    fastcgi_temp_path ${temporaryDirectory}/nginx-fastcgi;
    uwsgi_temp_path ${temporaryDirectory}/nginx-uwsgi;
    scgi_temp_path ${temporaryDirectory}/nginx-scgi;
    # The address of the proxy, not of a reader. Visitor addresses are logged
    # by the public host, which is the one place that has to see them.
    access_log ${accessLog};

    include ${includeGlob};
}
`;
}

/**
 * The Apache fragment for the canonical host in front of the container. It
 * forwards and adds nothing: the container sets the security headers, the
 * cache rules and the redirects, so they exist in one place only.
 */
export function renderApacheProxy({
  canonicalHost,
  containerHost,
  containerPort,
  passThroughPrefixes,
  generator = 'apps/website/scripts/emit-site.mjs',
}: {
  canonicalHost: string;
  containerHost: string;
  containerPort: number;
  passThroughPrefixes: readonly string[];
  generator?: string;
}): string {
  return `${header(generator)}
# Reverse proxy for the Koxora marketing website on ${canonicalHost}. Place it
# in the HTTPS virtual host of that name. The container answers on
# ${containerHost}:${containerPort} and is not reachable from outside the host.
#
# Nothing is added here. Security headers, cache rules, redirects and the
# language decision all come from the container, so one release changes all of
# them at once; a header set here as well would silently win and drift.

<IfModule mod_proxy.c>
  ProxyPreserveHost On
  ProxyAddHeaders On
  # Certificate issuance and mail autodiscovery stay with the host that owns
  # them. They are excluded before the catch-all, because the first matching
  # ProxyPass wins.
${passThroughPrefixes.map((prefix) => `  ProxyPass ${prefix} !`).join('\n')}
  ProxyPass / http://${containerHost}:${containerPort}/
  ProxyPassReverse / http://${containerHost}:${containerPort}/
  <IfModule mod_headers.c>
    RequestHeader set X-Forwarded-Proto "https"
  </IfModule>
</IfModule>
`;
}

/**
 * The contact endpoint's Apache rules, and nothing else.
 *
 * This is a separate file from the virtual host fragment on purpose, and the
 * reason is worth stating because getting it wrong is a security problem
 * rather than a misconfiguration.
 *
 * The rules below have to live **inside one `<VirtualHost>`** — the HTTPS host
 * of the canonical domain. Enabled server-wide instead, with `a2enconf` or a
 * file in `conf-enabled`, they would apply to every virtual host the server
 * has: `/api/contact` would be aliased on unrelated sites, and anything else
 * in the same file would leak with it. The earlier draft of the operator
 * document offered exactly that as a fallback, and the Product Owner was
 * right to have it removed.
 *
 * It also deliberately carries **no proxy rule for the website**. The running
 * deployment already has a working reverse proxy to the container; this file
 * adds one exclusion to it and maps one path, so nothing is set up twice and
 * nothing already working is overwritten.
 *
 * `script` is the single file the web server may execute and `fpm` is the
 * address it is handed to. Both come from the host, because a guessed
 * deployment path generates a rule that points at nothing.
 */
export function renderApacheContact({
  path,
  script,
  fpm,
  canonicalHost,
  generator = 'apps/website/scripts/emit-site.mjs',
}: {
  path: string;
  script: string;
  fpm: string;
  canonicalHost: string;
  generator?: string;
}): string {
  return `${header(generator)}
# The contact endpoint of ${canonicalHost}.
#
# INCLUDE THIS INSIDE THE HTTPS <VirtualHost> OF ${canonicalHost}, AND NOWHERE
# ELSE. It must not be enabled server-wide: a file in conf-enabled, or
# a2enconf, applies to every virtual host on this server, and ${path} would
# then be mapped on sites that have nothing to do with Koxora.
#
# Include it BEFORE that host's existing "ProxyPass /" line. The first
# matching ProxyPass wins, so an exclusion that comes after the catch-all
# never fires and every submission would reach the static website container
# instead of PHP.
#
# It adds no proxy rule for the website itself. The existing reverse proxy to
# the container stays exactly as it is.

<IfModule mod_proxy.c>
  # Keep the submission path away from the catch-all that serves the site.
  ProxyPass ${path} !
</IfModule>
<IfModule mod_alias.c>
  # One address, one file. The endpoint's code, settings and dependencies are
  # outside every document root, so there is nothing else here to reach.
  Alias ${path} "${script}"
</IfModule>
<Directory "${dirname(script)}">
  # Everything in this directory is denied, and one file is granted back.
  # Both the permission and the handler are scoped to this directory on
  # purpose: a <Files> section at the top of a virtual host would apply to
  # every directory it serves, and would hand any file of the same name
  # anywhere on the site to PHP.
  Options -Indexes -FollowSymLinks -ExecCGI
  AllowOverride None
  Require all denied
  <Files "${basename(script)}">
    Require all granted
    <IfModule mod_proxy_fcgi.c>
      SetHandler "proxy:${fpm}"
    </IfModule>
  </Files>
</Directory>
`;
}

/** The last segment of a POSIX path, without pulling in a Node module: this
 * file is also bundled for the browser build. */
function basename(path: string): string {
  const parts = path.split('/');
  return parts[parts.length - 1] ?? path;
}
/** Everything before the last segment, with no trailing slash. */
function dirname(path: string): string {
  const cut = path.lastIndexOf('/');
  return cut <= 0 ? '/' : path.slice(0, cut);
}
/**
 * The Apache fragment that makes every other host a redirect to the canonical
 * one. The target is the configured canonical origin, written into the file:
 * it is never built from the request, so no `Host` header can turn this into
 * an open redirect.
 */
export function renderApacheAliases({
  canonicalOrigin,
  aliasHosts,
  status,
  passThroughPrefixes,
  generator = 'apps/website/scripts/emit-site.mjs',
}: {
  canonicalOrigin: string;
  aliasHosts: readonly string[];
  status: 301 | 308;
  passThroughPrefixes: readonly string[];
  generator?: string;
}): string {
  const exclusion = passThroughPrefixes
    .map((prefix) => literal(prefix.replace(/^\//, '')))
    .join('|');
  // The path is taken from the request target and appended to a fixed origin;
  // Apache appends the original query string when the target carries none.
  const rule = `  RedirectMatch ${status} "^/(?!${exclusion})(.*)$" "${canonicalOrigin}/$1"`;
  const host = (name: string, port: number) => `<VirtualHost *:${port}>
  ServerName ${name}
  ${port === 80 ? '# Plain HTTP is answered only to send the reader to HTTPS on the\n  # canonical host; certificate issuance over HTTP-01 stays local.' : '# A valid certificate for this name has to be installed and renewed, or a\n  # browser reports a certificate error before it ever sees this redirect.'}
${rule}
</VirtualHost>`;
  return `${header(generator)}
# Canonical host redirects for the Koxora marketing website.
#
# ${canonicalOrigin} is the only address of this site. Every other name that
# answers sends the reader there with the path and the query it was asked for,
# so a deep link keeps working and the root of an alias is negotiated for its
# language by the canonical host.
#
# Three properties are deliberate:
#   * the target is the fixed origin above, never the request's own Host, so
#     this cannot become an open redirect;
#   * these paths are answered locally, so certificate renewal and mail
#     autodiscovery keep working on these domains:
${passThroughPrefixes.map((prefix) => `#       ${prefix}`).join('\n')}
#   * each name needs its own valid certificate, because a browser completes
#     TLS before it is told to go somewhere else.
#
# Roll out with a temporary 302 first and change it to ${status} once the
# answers are verified: a permanent redirect is cached and hard to take back.

${aliasHosts.flatMap((name) => [host(name, 80), host(name, 443)]).join('\n')}
`;
}

/**
 * The Apache fragment for serving the emitted files directly, without a
 * container. It is what the W1 deployment used and what a host without Docker
 * still needs; the language decision is the simpler one a rewrite can express.
 */
export function renderApacheStatic({
  locales,
  defaultLocale,
  redirects,
  headers,
  cacheRules,
  documentCacheControl,
  languageCookieName,
  generator = 'apps/website/scripts/emit-site.mjs',
}: HostingInput): string {
  const cookiePattern = literal(languageCookieName);
  return `${header(generator)}
# Virtual host fragment for the Koxora marketing website, served from the
# emitted files. The browser studio is a separate deployment on its own host
# and is never served from this root.
# Regenerate and reload this file with every release: it pins the inline
# scripts of the build by hash.
Options -Indexes +SymLinksIfOwnerMatch
<IfModule mod_headers.c>
${Object.entries(headers)
  .map(([name, value]) => `  Header always set ${name} "${value}"`)
  .join('\n')}
${cacheRules
  .map(
    (rule) =>
      `  <LocationMatch "^${rule.prefix}">\n    Header always set Cache-Control "${rule.value}"\n  </LocationMatch>`,
  )
  .join('\n')}
  <LocationMatch "\\.html$">
    Header always set Cache-Control "${documentCacheControl}"
  </LocationMatch>
  # The negotiated root depends on the reader, so it is never stored.
  <LocationMatch "^/$">
    Header always set Cache-Control "no-store"
    Header always set Vary "Cookie, Accept-Language"
  </LocationMatch>
</IfModule>

DirectoryIndex index.html
ErrorDocument 404 /404.html
${locales
  .map(
    (locale) =>
      `<LocationMatch "^/${locale}/">\n  ErrorDocument 404 /${locale}/404.html\n</LocationMatch>`,
  )
  .join('\n')}

# Build artefacts and dot files are never public, whatever ends up in the root.
# The standard well-known directory is the one exception; it exists to be read.
RedirectMatch 404 "${hiddenPathPattern}"

<IfModule mod_rewrite.c>
  RewriteEngine On
  # Language negotiation for the root document only, in the documented order:
  # an explicit stored choice first, then the languages of the request, then
  # the fallback. Every other address names its language and is left alone.
  # In a virtual host the matched path starts with a slash, hence ^/?$.
${locales
  .map(
    (locale) =>
      `  RewriteCond %{HTTP_COOKIE} (^|;)\\s*${cookiePattern}=${locale}\\s*(;|$) [NC]\n  RewriteRule ^/?$ /${locale}/ [R=302,L]`,
  )
  .join('\n')}
  # A rewrite condition cannot compare quality values, so the conditions are
  # ordered by list position and the first supported entry wins. Browsers
  # write the list in descending quality, so this agrees with the
  # authoritative algorithm in apps/website/src/language.ts, which runs in the
  # browser and in the reference server.
${acceptLanguagePatterns(locales)
  .map(
    ({ locale, position, pattern }) =>
      `  # entry ${position + 1} of the list\n  RewriteCond %{HTTP:Accept-Language} "${pattern}" [NC]\n  RewriteRule ^/?$ /${locale}/ [R=302,L]`,
  )
  .join('\n')}
  RewriteRule ^/?$ /${defaultLocale}/ [R=302,L]
  # Add the trailing slash so every page has exactly one address. The capture
  # never starts with a slash, so the target can never become protocol-relative.
  RewriteCond %{REQUEST_URI} !\\.[a-zA-Z0-9]+$
  RewriteRule ^/?(.*[^/])$ /$1/ [R=301,L]
</IfModule>

# Both spellings are matched, so an address without its trailing slash does
# not take a second hop through the slash rule above.
${redirects
  .map((entry) => {
    const pattern = entry.from.replace(/\/$/, '').replace(/\//g, '\\/');
    return `RedirectMatch ${entry.status} "^${pattern}\\/?$" "${entry.to}"`;
  })
  .join('\n')}
`;
}
